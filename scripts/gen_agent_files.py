#!/usr/bin/env python3
"""Generates site/agents.txt and site/.well-known/agents.json, the rules for AI agents, from data/site.json.

Both files say what an agent may and may not do on the site, and point to the
sitemap, llms.txt and the booking link. The booking link is the only contact:
no email address goes into a generated file. The format matches the other Junto
sites. Run directly (`python3 scripts/gen_agent_files.py`) or through `make sync`.
"""
import json
import pathlib

from lib_blocks import write_if_changed
from lib_site import REPO_ROOT, load_site

HEADER = "# Generated by scripts/gen_agent_files.py from data/site.json. Do not edit."


def render_agents_txt(site: dict) -> str:
    agents = site["seo"]["agents"]
    base = site["base_url"]
    lines = [
        HEADER,
        f"Name: {site['name']}",
        f"Site: {base}/",
        f"Summary: {agents['summary']}",
        *[f"Allow: {rule}" for rule in agents["may"]],
        *[f"Disallow: {rule}" for rule in agents["may_not"]],
        f"Contact: {site['cal']}",
        f"Sitemap: {base}/sitemap.xml",
        f"LLMs: {base}/llms.txt",
    ]
    return "\n".join(lines) + "\n"


def render_agents_json(site: dict) -> str:
    agents = site["seo"]["agents"]
    base = site["base_url"]
    data = {
        "name": site["name"],
        "url": f"{base}/",
        "summary": agents["summary"],
        "mayDo": agents["may"],
        "mayNotDo": agents["may_not"],
        "contact": site["cal"],
        "sitemap": f"{base}/sitemap.xml",
        "llms": f"{base}/llms.txt",
    }
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


FILES = {"agents.txt": render_agents_txt, ".well-known/agents.json": render_agents_json}


def write_file(path: pathlib.Path, text: str) -> bool:
    path.parent.mkdir(parents=True, exist_ok=True)
    return write_if_changed(path, text)


def sync(repo_root: pathlib.Path) -> list[str]:
    """Writes each file that changed. Returns the names it wrote."""
    site = load_site(repo_root)
    site_dir = repo_root / "site"
    return [name for name, render in FILES.items() if write_file(site_dir / name, render(site))]


def main():
    changed = sync(REPO_ROOT)
    for name in changed:
        print(f"updated site/{name}")
    if not changed:
        print("agent files already in sync")


if __name__ == "__main__":
    main()
